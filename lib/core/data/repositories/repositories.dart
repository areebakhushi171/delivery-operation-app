import '../models/models.dart';

abstract class AuthRepository {
  Future<AppUser?> restoreSession();
  Future<AppUser> signIn({
    required String identifier,
    required String password,
    required UserRole role,
  });
  Future<AppUser> signUpRider({
    required String name,
    required String email,
    required String phone,
    required String password,
    required String vehicleType,
    required String vehicleReg,
  });
  Future<void> signOut();
  Future<void> sendPasswordReset(String email);
}

abstract class OrderRepository {
  Stream<List<DeliveryOrder>> watchAllOrders();
  Stream<List<DeliveryOrder>> watchRiderOrders(String riderId);

  /// Order id is generated by the backend (no duplicates).
  Future<DeliveryOrder> createOrder(DeliveryOrder draft, String byUid);
  Future<void> assignRider({required String orderId, required String riderId, required String byUid});

  /// Rider-only, forward-only, idempotent. `delivered` must go through [submitProof].
  Future<void> updateStatus({required String orderId, required OrderStatus next, required String byUid});
  Future<void> submitProof({required DeliveryProof proof, required String byUid});
  Future<void> reschedule({
    required String orderId,
    required DateTime start,
    required DateTime end,
    required String byUid,
  });
  Future<void> cancelOrder({required String orderId, required String byUid, String? reason});
  Future<void> reconcileCod({required String orderId, required String byUid});
}

abstract class RiderRepository {
  Stream<List<Rider>> watchRiders();
  Stream<Rider?> watchRider(String riderId);
  Future<void> setDuty(String riderId, DutyStatus duty);
  Future<void> updateTelemetry(
    String riderId, {
    required double lat,
    required double lng,
    double? speedKmh,
    double? heading,
    int? battery,
  });
  Future<void> updateProfile(String riderId, {required String name, required String phone});
}

abstract class ExceptionRepository {
  Stream<List<DeliveryException>> watchAll();
  Stream<List<DeliveryException>> watchForRider(String riderId);
  Future<void> report(DeliveryException exception, String byUid);
  Future<void> resolve({
    required String exceptionId,
    required ExceptionStatus outcome,
    required String byUid,
    String? note,
    String? newRiderId,
    DateTime? newStart,
    DateTime? newEnd,
  });
}

abstract class NotificationRepository {
  Stream<List<AppNotification>> watch(String recipientId);
  Future<void> send(AppNotification notification);
  Future<void> markRead(String id);
  Future<void> markAllRead(String recipientId);
}

class AppRepositories {
  const AppRepositories({
    required this.auth,
    required this.orders,
    required this.riders,
    required this.exceptions,
    required this.notifications,
  });

  final AuthRepository auth;
  final OrderRepository orders;
  final RiderRepository riders;
  final ExceptionRepository exceptions;
  final NotificationRepository notifications;
}
